-- =============================================
-- ANALYTICS LAYER
-- =============================================


-- 1. Monthly financial summary
CREATE OR REPLACE VIEW PERSONAL_FINANCE_DB.ANALYTICS.MONTHLY_SUMMARY AS

SELECT
    YEAR(TRANSACTION_DATE) AS YEAR,
    MONTH(TRANSACTION_DATE) AS MONTH,

    SUM(
        CASE
            WHEN TYPE = 'Income' THEN AMOUNT
            ELSE 0
        END
    ) AS TOTAL_INCOME,

    SUM(
        CASE
            WHEN TYPE = 'Expense' THEN AMOUNT
            ELSE 0
        END
    ) AS TOTAL_EXPENSES,

    SUM(
        CASE
            WHEN TYPE = 'Income' THEN AMOUNT
            ELSE 0
        END
    )
    -
    SUM(
        CASE
            WHEN TYPE = 'Expense' THEN AMOUNT
            ELSE 0
        END
    ) AS NET_SAVINGS

FROM PERSONAL_FINANCE_DB.RAW.TRANSACTIONS

GROUP BY
    YEAR(TRANSACTION_DATE),
    MONTH(TRANSACTION_DATE);


-- 2. Category spending
CREATE OR REPLACE VIEW PERSONAL_FINANCE_DB.ANALYTICS.CATEGORY_SPENDING AS

SELECT
    YEAR(TRANSACTION_DATE) AS YEAR,
    MONTH(TRANSACTION_DATE) AS MONTH,
    CATEGORY,
    SUM(AMOUNT) AS TOTAL_EXPENSE

FROM PERSONAL_FINANCE_DB.RAW.TRANSACTIONS

WHERE TYPE = 'Expense'

GROUP BY
    YEAR(TRANSACTION_DATE),
    MONTH(TRANSACTION_DATE),
    CATEGORY;


-- 3. Fixed vs Variable spending
CREATE OR REPLACE VIEW PERSONAL_FINANCE_DB.ANALYTICS.FIXED_VARIABLE_SPENDING AS

SELECT
    YEAR(TRANSACTION_DATE) AS YEAR,
    MONTH(TRANSACTION_DATE) AS MONTH,
    FIXED_VARIABLE,
    SUM(AMOUNT) AS TOTAL_EXPENSE

FROM PERSONAL_FINANCE_DB.RAW.TRANSACTIONS

WHERE TYPE = 'Expense'

GROUP BY
    YEAR(TRANSACTION_DATE),
    MONTH(TRANSACTION_DATE),
    FIXED_VARIABLE;


-- 4. Month-over-Month expense trend
CREATE OR REPLACE VIEW PERSONAL_FINANCE_DB.ANALYTICS.MONTHLY_TRENDS AS

WITH MONTHLY AS (
    SELECT
        YEAR,
        MONTH,
        TOTAL_EXPENSES,

        LAG(TOTAL_EXPENSES)
        OVER (ORDER BY YEAR, MONTH) AS PREV_MONTH_EXPENSE

    FROM PERSONAL_FINANCE_DB.ANALYTICS.MONTHLY_SUMMARY
)

SELECT
    YEAR,
    MONTH,
    TOTAL_EXPENSES,
    PREV_MONTH_EXPENSE,

    ROUND(
        (TOTAL_EXPENSES - PREV_MONTH_EXPENSE) * 100
        / NULLIF(PREV_MONTH_EXPENSE, 0),
        2
    ) AS MOM_PERCENT_CHANGE

FROM MONTHLY;