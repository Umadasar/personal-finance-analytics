-- Raw transaction table
-- Preserves source-level personal finance data

CREATE TABLE IF NOT EXISTS PERSONAL_FINANCE_DB.RAW.TRANSACTIONS (
    TRANSACTION_DATE DATE,
    YEAR NUMBER(4,0),
    MONTH VARCHAR(10),
    DESCRIPTION VARCHAR(255),
    CATEGORY VARCHAR(100),
    SUBCATEGORY VARCHAR(100),
    TYPE VARCHAR(20),
    PAYMENT_METHOD VARCHAR(50),
    FIXED_VARIABLE VARCHAR(20),
    NEEDS_WANTS VARCHAR(20),
    AMOUNT NUMBER(12,2)
);